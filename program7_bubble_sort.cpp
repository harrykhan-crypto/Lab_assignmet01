// Program 7: Sort an array in ascending order using bubble sort
#include <iostream>
using namespace std;

int main() {
    const int MAX = 100;
    int arr[MAX];
    int n;

    cout << "Enter number of elements (1-" << MAX << "): ";
    cin >> n;

    if (n < 1 || n > MAX) {
        cout << "Invalid size." << endl;
        return 1;
    }

    cout << "Enter " << n << " elements: ";
    for (int i = 0; i < n; i++) {
        cin >> arr[i];
    }

    for (int i = 0; i < n - 1; i++) {
        bool swapped = false;
        for (int j = 0; j < n - 1 - i; j++) {
            if (arr[j] > arr[j + 1]) {
                int temp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = temp;
                swapped = true;
            }
        }
        if (!swapped) {
            break;
        }
    }

    cout << "Sorted array: ";
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;

    return 0;
}
